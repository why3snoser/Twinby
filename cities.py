def get_cities(min_population=0):
    """Return cities filtered by minimum population."""
    return [
        {"name": name, "lat": lat, "lon": lon, "population": pop}
        for name, lat, lon, pop in RUSSIAN_CITIES
        if pop >= min_population
    ]


def get_cities_json():
    """Return all cities as JSON-serializable list."""
    return [
        {"name": name, "lat": lat, "lon": lon, "population": pop}
        for name, lat, lon, pop in RUSSIAN_CITIES
    ]
