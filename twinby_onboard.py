#!/usr/bin/env python3
"""
Twinby (web) onboarding client.  Source of truth: HAR recorded 2026-11-20 on https://twinby.ru/app
NOT RUN HERE: written from the HAR only, never executed against the live site.

What it does (order and bodies copied from the HAR):
  1. POST /api/auth/v3/oauth/by-token   -> accessToken / refreshToken   (VK flow, see AUTH below)
  2. POST /api/users/agreement/
  3. PATCH /api/users/me/               name, birthday, gender, targetId, onboardingStep 1..6
  4. PATCH /api/users/me/filter/
  5. POST  /api/photo/                  multipart, field "file"
  6. POST  /api/dating/answers/         10 answers, values 1..7
  7. PATCH /api/users/me/               {"onboardingCompleted": true}

AUTH (important):
  The HAR shows registration through VK ID (provider "vk"). The body for by-token contains a one-time
  VK code plus codeVerifier/deviceId/state generated by the VK SDK in the browser. Those cannot be
  produced offline: log in to VK in the browser, copy the by-token JSON body from DevTools and pass it
  with --oauth-body. The code is single use and short lived.
  The "email" provider exists (auth/v3/auth/providers/all) but its endpoints are NOT in the HAR: unknown.
  Alternatively pass --access-token of an already created session and only the onboarding part runs.

Usage:
  pip install httpx
  python twinby_onboard.py --oauth-body oauth.json --name Имя --birthday 2000-01-31 --gender m \
      --photo me.webp --interview-id <id> [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

import httpx

# ---- config: everything build-dependent lives here (source: HAR 2026-11-20) -------------------
BASE = "https://twinby.ru"
API = {
    "captcha_cfg": "/api/auth/v1/captcha/config",       # HAR: {"isActive": false}
    "oauth_by_token": "/api/auth/v3/oauth/by-token",
    "agreement": "/api/users/agreement/",
    "me": "/api/users/me/",
    "filter": "/api/users/me/filter/",
    "photo": "/api/photo/",
    "targets": "/api/user-target/",
    "interviews": "/api/dating/interview/",
    "questions": "/api/dating/public-interview/{iid}/questions/?lang=ru",
    "answers": "/api/dating/answers/",
}
AUTH_SCHEME = "JWT"   # HAR bundle: Authorization: `JWT ${accessToken}`
ORIGIN_HEADERS = {"Origin": BASE, "Referer": f"{BASE}/app/onboarding"}
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36"
# HAR values observed for the filter; "n" = any gender, distance 99. Uncalibrated defaults, change freely.
FILTER_DEFAULT = {"minAges": 18, "maxAges": 80, "distance": 99, "gender": "n"}
# --------------------------------------------------------------------------------------------


def valid_birthday(s: str) -> str:
    d = date.fromisoformat(s)
    age = (date.today() - d).days // 365
    if age < 18 or age > 100:
        raise SystemExit("birthday: age must be 18..100")
    return f"{d.isoformat()}T00:00:00.000Z"      # HAR format


class Client:
    def __init__(self, dry: bool) -> None:
        self.dry = dry
        self.http = httpx.Client(base_url=BASE, timeout=30, headers={"User-Agent": UA, "Accept": "application/json, text/plain, */*", **ORIGIN_HEADERS})

    def auth(self, token: str) -> None:
        self.http.headers["Authorization"] = f"{AUTH_SCHEME} {token}"

    def call(self, method: str, path: str, **kw) -> dict | list:
        print(f"{method} {path} {'[dry-run, not sent]' if self.dry and method != 'GET' else ''}")
        if self.dry and method != "GET":
            return {}
        r = self.http.request(method, path, **kw)
        if r.status_code >= 400:
            raise SystemExit(f"{method} {path} -> {r.status_code}: {r.text[:300]}")
        return r.json() if r.content else {}


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--oauth-body", help="JSON file with the by-token request body copied from DevTools (VK)")
    p.add_argument("--access-token", help="use an existing session instead of by-token")
    p.add_argument("--name", required=True)
    p.add_argument("--birthday", required=True, help="YYYY-MM-DD")
    p.add_argument("--gender", required=True, choices=["m", "f"])   # HAR shows "m"; "f" is assumed, verify
    p.add_argument("--photo", required=True, help="image file (HAR upload was image/webp)")
    p.add_argument("--target-id", help="id from /api/user-target/ ; omit to list and stop")
    p.add_argument("--interview-id", help="test id (HAR: URL /app/tests/<id>) ; omit to list and stop")
    p.add_argument("--dry-run", action="store_true")
    a = p.parse_args()

    birthday = valid_birthday(a.birthday)
    photo = Path(a.photo)
    if not photo.is_file() or photo.stat().st_size > 10_000_000:
        raise SystemExit("photo missing or > 10 MB")

    c = Client(a.dry_run)

    cfg = c.call("GET", API["captcha_cfg"])
    if isinstance(cfg, dict) and cfg.get("isActive"):
        raise SystemExit("Captcha is active on the site: this tool does not solve it. Do the sign-in step in the browser.")

    if a.access_token:
        c.auth(a.access_token)
    else:
        if not a.oauth_body:
            raise SystemExit("need --oauth-body or --access-token")
        raw = Path(a.oauth_body).read_text(encoding="utf-8-sig").strip()
        # accepts: bare JSON, "--data-raw '{...}'", or a whole "Copy as cURL" dump
        m = re.search(r"--data-raw\s+\$?'(\{.*?\})'", raw, re.S) or re.search(r'--data-raw\s+"(\{.*?\})"', raw, re.S)
        if m:
            raw = m.group(1)
        raw = raw.strip("'\"")
        if not raw:
            raise SystemExit(f"{a.oauth_body} is empty: paste the JSON body into it and save the file")
        try:
            body = json.loads(raw)
        except json.JSONDecodeError as e:
            raise SystemExit(f"{a.oauth_body} is not valid JSON ({e}). It must start with {{\"provider\":\"vk\"")
        if body.get("provider") != "vk" or "options" not in body:
            raise SystemExit("oauth body must look like the HAR one: {provider:'vk', options:{code,codeVerifier,deviceId,state,redirectUri}}")
        tok = c.call("POST", API["oauth_by_token"], json=body)
        if not a.dry_run:
            c.auth(tok["accessToken"])   # refreshToken arrives in body; refresh endpoint wants it as cookie 'refresh_token'
            # keep the session so a failed run can be resumed with --access-token (the VK code is single use)
            Path("session.json").write_text(json.dumps(tok), encoding="utf-8")
            print("session saved to session.json (treat as a password)")

    if not a.target_id or not a.interview_id:
        print("\ntargets:", json.dumps(c.call("GET", API["targets"]), ensure_ascii=False)[:1500])
        print("interviews:", json.dumps(c.call("GET", API["interviews"]), ensure_ascii=False)[:1500])
        raise SystemExit("\nPass --target-id and --interview-id (taken from the lists above) and run again.")

    c.call("POST", API["agreement"])                                   # HAR: empty body, accepts policy+agreement
    c.call("PATCH", API["me"], json={"name": a.name, "language": "RU"})
    c.call("PATCH", API["me"], json={"birthday": birthday})
    c.call("PATCH", API["me"], json={"onboardingStep": 1})
    c.call("PATCH", API["filter"], json=FILTER_DEFAULT)
    c.call("PATCH", API["me"], json={"gender": a.gender})
    c.call("PATCH", API["me"], json={"onboardingStep": 2})
    c.call("PATCH", API["me"], json={"onboardingStep": 3})
    c.call("PATCH", API["me"], json={"targetId": a.target_id})
    c.call("PATCH", API["me"], json={"onboardingStep": 4})

    mime = {".webp": "image/webp", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png"}.get(photo.suffix.lower())
    if not mime:
        raise SystemExit("photo must be .webp/.jpg/.png")
    c.call("POST", API["photo"], files={"file": (photo.name, photo.read_bytes(), mime)})
    c.call("PATCH", API["me"], json={"onboardingStep": 5})
    c.call("PATCH", API["me"], json={"onboardingStep": 6})

    qs = c.call("GET", API["questions"].format(iid=a.interview_id))
    if not a.dry_run:
        if not isinstance(qs, list) or not qs:
            raise SystemExit("no questions returned")
        # HAR answers: integer 1..7 per question. These are placeholders chosen by you, not calibrated data.
        answers = [{"question": q["id"], "answer": 4} for q in qs]
        c.call("POST", API["answers"], json={"test": answers})
    c.call("PATCH", API["me"], json={"onboardingCompleted": True})

    me = c.call("GET", API["me"])
    if isinstance(me, dict) and me:
        print("done:", {k: me.get(k) for k in ("id", "name", "onboardingCompleted", "moderationStatus")})


if __name__ == "__main__":
    sys.exit(main())
