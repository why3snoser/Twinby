"""
mitmproxy addon: intercept Twinby liveness POST and swap video data,
keeping the original twpd atom intact.

Usage:
  mitmweb --ssl-insecure -s swap_video.py --set swap_video_path=/path/to/your/video.mp4

The swap video must be a valid MP4 file (the one generated by convert_to_android.py
but WITHOUT the twpd/wide atom — just ftyp+moov+mdat).
"""

import os
import struct
import logging
from mitmproxy import ctx, http

logger = logging.getLogger(__name__)


def parse_mp4_atoms(data: bytes) -> list:
    """Parse MP4 top-level atoms, return list of (name, offset, size, data)."""
    atoms = []
    pos = 0
    while pos < len(data) - 8:
        size = struct.unpack('>I', data[pos:pos+4])[0]
        name = data[pos+4:pos+8]
        if size < 8 or pos + size > len(data):
            break
        atoms.append({
            'name': name,
            'offset': pos,
            'size': size,
            'data': data[pos:pos+size],
        })
        pos += size
    return atoms


def extract_twpd_wide(atoms: list) -> bytes | None:
    """Find the 'wide' atom that contains 'twpd' sub-atom."""
    for atom in atoms:
        if atom['name'] == b'wide':
            # Check if it contains twpd
            ad = atom['data']
            if b'twpd' in ad:
                return ad
    # Also check for standalone twpd atom
    for atom in atoms:
        if atom['name'] == b'twpd':
            return atom['data']
    return None


def build_swapped_mp4(original_mp4: bytes, swap_mp4: bytes) -> bytes | None:
    """
    Take original_mp4 (from real app, has valid twpd),
    take swap_mp4 (our video without twpd),
    return: swap_mp4's video content + original's twpd/wide atom.
    """
    orig_atoms = parse_mp4_atoms(original_mp4)
    swap_atoms = parse_mp4_atoms(swap_mp4)

    if not orig_atoms or not swap_atoms:
        logger.error("Failed to parse MP4 atoms")
        return None

    # Extract twpd-containing wide atom from original
    twpd_wide = extract_twpd_wide(orig_atoms)
    if not twpd_wide:
        logger.error("No twpd/wide atom found in original MP4")
        return None

    logger.info(f"Found twpd/wide atom: {len(twpd_wide)} bytes")

    # Build new MP4: swap video's atoms + original's wide/twpd
    # Typical order: ftyp, wide(twpd), mdat, moov  OR  ftyp, moov, wide(twpd), mdat
    # We need to match the original's atom order but with swap's content

    # Strategy: take all atoms from swap video, insert twpd/wide
    # in the same relative position as in original
    result = bytearray()

    # Find where wide/twpd was in original (before or after mdat?)
    orig_atom_names = [a['name'] for a in orig_atoms]
    wide_before_mdat = False
    wide_idx = -1
    mdat_idx = -1
    for i, a in enumerate(orig_atoms):
        if a['name'] == b'wide' and b'twpd' in a['data']:
            wide_idx = i
        if a['name'] == b'mdat':
            mdat_idx = i
    if wide_idx >= 0 and mdat_idx >= 0:
        wide_before_mdat = wide_idx < mdat_idx

    logger.info(f"Original atom order: {[a['name'].decode('ascii','replace') for a in orig_atoms]}")
    logger.info(f"Swap atom order: {[a['name'].decode('ascii','replace') for a in swap_atoms]}")
    logger.info(f"wide_before_mdat: {wide_before_mdat}")

    # Remove any existing wide atom from swap video
    swap_filtered = [a for a in swap_atoms if not (a['name'] == b'wide' and b'twpd' in a['data'])]
    # Also remove standalone twpd if present
    swap_filtered = [a for a in swap_filtered if a['name'] != b'twpd']

    # Insert twpd/wide in correct position
    inserted = False
    for a in swap_filtered:
        if a['name'] == b'mdat' and wide_before_mdat and not inserted:
            result.extend(twpd_wide)
            inserted = True
            logger.info(f"Inserted twpd/wide before mdat")
        result.extend(a['data'])
        if a['name'] == b'mdat' and not wide_before_mdat and not inserted:
            result.extend(twpd_wide)
            inserted = True
            logger.info(f"Inserted twpd/wide after mdat")

    if not inserted:
        # Fallback: append at end
        result.extend(twpd_wide)
        logger.info(f"Inserted twpd/wide at end")

    return bytes(result)


def find_mp4_in_multipart(body: bytes, boundary: bytes) -> tuple:
    """
    Find the MP4 video part in multipart form data.
    Returns (start_offset, end_offset) of the MP4 data within the body,
    and the header bytes before the MP4 data.
    """
    # Split by boundary
    parts = body.split(b'--' + boundary)
    offset = 0
    for i, part in enumerate(parts):
        if b'video/mp4' in part or b'name="data"' in part:
            # Find the double CRLF that separates headers from body
            header_end = part.find(b'\r\n\r\n')
            if header_end < 0:
                header_end = part.find(b'\n\n')
                sep_len = 2
            else:
                sep_len = 4

            if header_end >= 0:
                mp4_start_in_part = header_end + sep_len
                # The part ends with \r\n before next boundary
                mp4_data = part[mp4_start_in_part:]
                if mp4_data.endswith(b'\r\n'):
                    mp4_data = mp4_data[:-2]

                # Calculate absolute offsets
                part_abs_start = body.find(part)
                abs_start = part_abs_start + mp4_start_in_part
                abs_end = part_abs_start + len(part)
                if body[abs_end-2:abs_end] == b'\r\n':
                    abs_end -= 2

                return abs_start, abs_end, part[:mp4_start_in_part], mp4_data

    return None, None, None, None


class VideoSwapper:
    def __init__(self):
        self.swap_video_path = None
        self.swap_video_data = None

    def load(self, loader):
        loader.add_option(
            name="swap_video_path",
            typespec=str,
            default="",
            help="Path to the MP4 file to swap in",
        )

    def configure(self, updated):
        if "swap_video_path" in updated:
            path = ctx.options.swap_video_path
            if path and os.path.exists(path):
                with open(path, 'rb') as f:
                    self.swap_video_data = f.read()
                logger.info(f"Loaded swap video: {path} ({len(self.swap_video_data)} bytes)")
            elif path:
                logger.error(f"Swap video not found: {path}")

    def request(self, flow: http.HTTPFlow):
        # Only intercept liveness POST
        if not flow.request.pretty_url.endswith('/api/photo/liveness/v2'):
            return
        if flow.request.method != 'POST':
            return

        logger.info(f"=== INTERCEPTED LIVENESS REQUEST ===")
        logger.info(f"Content-Length: {len(flow.request.content)}")

        if not self.swap_video_data:
            logger.warning("No swap video loaded! Set --set swap_video_path=/path/to/video.mp4")
            return

        content_type = flow.request.headers.get('content-type', '')
        if 'boundary=' not in content_type:
            logger.error("No multipart boundary found")
            return

        boundary = content_type.split('boundary=')[1].strip().encode()
        body = flow.request.content

        mp4_start, mp4_end, part_header, orig_mp4 = find_mp4_in_multipart(body, boundary)
        if orig_mp4 is None:
            logger.error("Could not find MP4 in multipart body")
            return

        logger.info(f"Found original MP4: {len(orig_mp4)} bytes at offset {mp4_start}-{mp4_end}")

        # Parse original MP4 and extract twpd
        orig_atoms = parse_mp4_atoms(orig_mp4)
        logger.info(f"Original atoms: {[(a['name'].decode('ascii','replace'), a['size']) for a in orig_atoms]}")

        twpd_wide = extract_twpd_wide(orig_atoms)
        if not twpd_wide:
            logger.error("No twpd in original MP4!")
            return

        logger.info(f"twpd/wide atom: {len(twpd_wide)} bytes")
        logger.info(f"twpd hex: {twpd_wide[:64].hex()}")

        # Build swapped MP4
        new_mp4 = build_swapped_mp4(orig_mp4, self.swap_video_data)
        if not new_mp4:
            logger.error("Failed to build swapped MP4")
            return

        logger.info(f"Swapped MP4: {len(new_mp4)} bytes (was {len(orig_mp4)})")

        # Verify new MP4 has twpd
        new_atoms = parse_mp4_atoms(new_mp4)
        logger.info(f"New atoms: {[(a['name'].decode('ascii','replace'), a['size']) for a in new_atoms]}")
        new_twpd = extract_twpd_wide(new_atoms)
        if new_twpd:
            logger.info(f"twpd verified in new MP4: {len(new_twpd)} bytes")
        else:
            logger.error("twpd MISSING from new MP4!")
            return

        # Replace in multipart body
        new_body = body[:mp4_start] + new_mp4 + body[mp4_end:]

        # Update content-length header
        flow.request.content = new_body
        flow.request.headers['content-length'] = str(len(new_body))

        logger.info(f"=== REQUEST MODIFIED ===")
        logger.info(f"Body: {len(body)} -> {len(new_body)} bytes")


addons = [VideoSwapper()]
